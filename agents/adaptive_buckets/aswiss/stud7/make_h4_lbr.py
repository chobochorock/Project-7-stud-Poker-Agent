"""Generate h4_lbr_generated.hpp: the engine's PolicyLBR and play_hand_policy_lbr with the target's H4 prior replaced
by the learned H4 likelihood, as in agents/cpp_mccfr/h4_ablation/run.py (same anchors, same replacement).

Usage (any directory): python make_h4_lbr.py
The output records the engine's sha256; aswiss_stud.cpp includes it. Rerun after the engine changes.
"""
import hashlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
ENGINE = HERE.parents[2] / "cpp_mccfr" / "stud_mccfr.cpp"


def between(source, first, last):
    if source.count(first) != 1 or source.count(last) != 1:
        raise ValueError(f"engine anchors changed: {first[:40]!r} / {last[:40]!r}")
    return source[source.index(first):source.index(last)]


source = ENGINE.read_text(encoding="utf-8")
lbr = between(source, "template <typename TargetPolicy>\nclass PolicyLBR {", "\nvoid apply_h4_choices(")
lbr = lbr.replace("PolicyLBR", "H4PolicyLBR")
old = """const int h4_ways = h4_multiplicity(
                {particle.target_hidden[0], particle.target_hidden[1]},
                target_public.front(),
                particle.target_discarded);"""
new = """const double h4_ways = target_.learned_h4()
                ? target_.h4_weight(
                    {particle.target_hidden[0], particle.target_hidden[1]},
                    target_public.front(), particle.target_discarded, target_seat)
                : h4_multiplicity(
                    {particle.target_hidden[0], particle.target_hidden[1]},
                    target_public.front(), particle.target_discarded);"""
if lbr.count(old) != 1:
    raise ValueError("H4 prior anchor changed")
lbr = lbr.replace(old, new)
match = between(source, "template <typename TargetPolicy>\ndouble play_hand_policy_lbr(",
                "\nstd::array<std::vector<PowerVector>, 3> collect_power_samples(")
match = match.replace("play_hand_policy_lbr", "play_hand_h4_lbr").replace("PolicyLBR<TargetPolicy>", "H4PolicyLBR<TargetPolicy>")
digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
out = HERE / "h4_lbr_generated.hpp"
out.write_text(f"// Generated by make_h4_lbr.py from cpp_mccfr/stud_mccfr.cpp (sha256 {digest}). Do not edit.\n"
               "// H4PolicyLBR = PolicyLBR whose target hidden-card prior uses target_.h4_weight() when\n"
               "// target_.learned_h4(); play_hand_h4_lbr = play_hand_policy_lbr using it.\n"
               + lbr + "\n" + match + "\n", encoding="utf-8")
print("wrote", out)
